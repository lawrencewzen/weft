import esbuild from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const entry = require.resolve('pi-antigravity-acp-provider/src/provider.ts');
const outfile = path.join(ROOT, 'src/vendor/antigravity-acp.mjs');

await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile,
  external: [
    '@earendil-works/pi-ai',
    '@agentclientprotocol/sdk',
    '@modelcontextprotocol/sdk',
    '@modelcontextprotocol/sdk/types.js',
    '@modelcontextprotocol/sdk/server/index.js',
    '@modelcontextprotocol/sdk/server/streamableHttp.js',
    'proper-lockfile',
    'unzipper',
    'zod',
    'typebox',
    'typebox/value',
  ],
  banner: {
    js: '/* Generated by scripts/bundle-antigravity-acp.mjs from pi-antigravity-acp-provider. Do not edit. */',
  },
  logLevel: 'info',
});
