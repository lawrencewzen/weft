const TARGET_MODEL_PROVIDERS = ['deepseek', 'anthropic', 'openai', 'moonshotai-cn', 'zai'];

const available = [];
for (const p of builtinProviders) {
  if (EXCLUDED.has(p.id)) continue;
  const authMethods = [];
  if (p.auth?.apiKey || !p.auth) authMethods.push('api_key');
  if (p.auth?.oauth) authMethods.push('oauth');
  const chatModels = p.getModels ? p.getModels().filter((m) => m.type === 'chat' || !m.type) : [];
  available.push({
    id: p.id,
    name: CN_NAME[p.id] || p.name || p.id,
    authMethods,
    modelCount: chatModels.length,
    popular: POPULAR.includes(p.id),
    ...(ENV_MAP[p.id] ? { envVar: ENV_MAP[p.id] } : {}),
    envDetected: p.id === 'moonshotai-cn',
    connected: false,
  });
}

// popular 优先，其余按 name 排序
available.sort((a, b) => {
  if (a.popular !== b.popular) return a.popular ? -1 : 1;
  return a.name.localeCompare(b.name, 'zh-CN');
});

const catalogModels = {};
for (const pid of TARGET_MODEL_PROVIDERS) {
  const p = builtinProviders.find((x) => x.id === pid);
  if (!p) continue;
  const list = p.getModels().filter((m) => m.type === 'chat' || !m.type);
  catalogModels[pid] = list.map((m) => ({
    id: m.id,
    name: m.name || m.id,
    brand: brandIdOf(icons.brandForModel(m.id)) || (pid === 'moonshotai-cn' ? 'Moonshot' : null),
    enabled: false,
    contextWindow: m.contextWindow ?? null,
    maxTokens: m.maxTokens ?? null,
    images: Boolean(m.input?.includes('image')),
    reasoning: Boolean(m.reasoning),
    overridden: {},
  }));
}

const fileContent = `/**
 * Generated by scripts/gen-mock-providers.mjs - DO NOT EDIT MANUALLY.
 * Re-generate with: node scripts/gen-mock-providers.mjs
 */
import type { Available, Model } from '../../src/data/providerTypes';

export const MOCK_AVAILABLE_PROVIDERS: Available[] = ${JSON.stringify(available, null, 2)};

export const MOCK_CATALOG_MODELS: Record<string, Model[]> = ${JSON.stringify(catalogModels, null, 2)};
`;

writeFileSync(OUT, fileContent, 'utf8');
console.log(`Generated ${OUT} with ${available.length} providers and models for ${Object.keys(catalogModels).join(', ')}.`);
